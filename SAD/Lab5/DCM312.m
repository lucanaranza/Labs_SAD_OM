function A312 = DCM312(phi, theta, psi)

    A312 = [ ...
        cos(psi)*cos(phi) - sin(psi)*sin(phi)*sin(theta), ...
        cos(psi)*sin(phi) + sin(psi)*cos(phi)*sin(theta), ...
       -sin(psi)*cos(theta);

       -sin(phi)*cos(theta), ...
        cos(phi)*cos(theta), ...
        sin(theta);

        sin(psi)*cos(phi) + cos(psi)*sin(phi)*sin(theta), ...
        sin(psi)*sin(phi) - cos(psi)*cos(phi)*sin(theta), ...
        cos(psi)*cos(theta) ...
    ];
   
end